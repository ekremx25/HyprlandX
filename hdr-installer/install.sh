#!/usr/bin/env bash
# Standalone installer: embedded PKGBUILD + patches. No backups are created.
set -Eeuo pipefail
mode=install
case "${1:-}" in
    '') ;;
    --check) mode=check ;;
    --build-only) mode=build ;;
    -h|--help)
        printf '%s\n' 'Usage: bash install.sh [--check | --build-only]' \
          'Arch/CachyOS x86_64; installed Hyprland 0.57.1 only.' \
          'No backups. No browser/profile/monitor configuration changes.' \
          'Run as your normal user. sudo is used by makepkg/pacman when necessary.' \
          'HDR_JOBS=2 by default. --build-only keeps the built package without installing.'
        exit 0 ;;
    *) printf 'Unknown option: %s\n' "$1" >&2; exit 2 ;;
esac
[[ $# -le 1 ]] || { echo 'Only one option is allowed.' >&2; exit 2; }
fail() { printf 'Error: %s\n' "$*" >&2; exit 1; }
[[ $EUID -ne 0 ]] || fail 'Run without sudo; makepkg must run as a normal user.'
[[ $(uname -m) == x86_64 ]] || fail 'Only x86_64 is supported.'
for tool in pacman makepkg git gcc tar base64 sha256sum mktemp; do
    command -v "$tool" >/dev/null || fail "Missing $tool. On Arch/CachyOS install base-devel and git first."
done
installed=$(pacman -Q hyprland 2>/dev/null) || fail 'The hyprland package must already be installed.'
installed=${installed#* }
[[ $installed =~ ^0\.57\.1([.-]|$) ]] || fail "Unsupported installed Hyprland version: $installed. Expected 0.57.1; no downgrade will be performed."
export HDR_JOBS=${HDR_JOBS:-2}
[[ $HDR_JOBS =~ ^[1-9][0-9]*$ ]] || fail 'HDR_JOBS must be a positive integer.'
printf 'Installed: %s\nSupported source: Hyprland 0.57.1\nBuild jobs: %s\nNo backups will be created.\n' "$installed" "$HDR_JOBS"
if [[ $mode == check ]]; then
    echo 'Preflight passed. Build dependencies and source compatibility are checked again during the build.'
    exit 0
fi
if [[ $mode == install && $installed == 0.57.1.hdrfix4-* ]]; then
    echo 'HDR fix 4 is already installed. Nothing to do.'
    exit 0
fi
work=$(mktemp -d "${TMPDIR:-/tmp}/hyprland-hdr.XXXXXXXX")
keep=0
cleanup() {
    result=$?
    if [[ $keep == 0 ]]; then rm -rf -- "$work"; fi
    if [[ $result != 0 ]]; then echo 'HDR installation did not complete.' >&2; fi
}
trap cleanup EXIT
trap 'exit 130' INT
trap 'exit 143' TERM
